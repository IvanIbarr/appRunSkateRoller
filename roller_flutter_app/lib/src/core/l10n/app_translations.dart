  static String translate(String languageCode, String key) {
    final lang = languageCode == 'en' ? 'en' : 'es';
    return _all[lang]?[key] ?? _all['es']?[key] ?? key;
  }

  /// `español` / `inglés` del perfil → código de idioma UI.
  static String localeCodeFromNacionalidad(String nacionalidad) {
    final n = nacionalidad.trim().toLowerCase();
    if (n == 'inglés' || n == 'ingles' || n == 'english') return 'en';
    return 'es';
  }
